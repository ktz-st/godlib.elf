; open_ugh STE port of TFMX (extracted from original/ugh_amiga/data/
; TFMX.obj via IRA, lives in reverse/TFMX.asm). The PLAYER LOGIC is
; intentionally not touched; only the hardware-address EQUs at the
; top get rerouted so every `move.w X,DMACON` etc lands in Leonard's
; emulated $DFF000 block (src/atari/leonardpaula.asm `custom`) and
; not on the Amiga custom chip. The linker patches the absolute
; addresses encoded in the original instructions when it resolves
; `TfmxCustom+$xxxx` to its final runtime location.
;
; Registers OUTSIDE the $DFF000 mirror that the player still touches
; (CIAA_PRA on Amiga = CIA-A; AUTO_INT3 = IRQ vector at $6C) get
; redirected to a small tfmxStubs scratch block so writes don't trash
; STE memory. They're never read by anyone that matters - on Amiga
; the bset/move would have armed an IRQ, on STE we drive the player
; manually from VBL so those side-effects are no-ops.
;
; xdef trampolines further down expose the six game-facing entry
; points (LAB_0841..LAB_0847 jump-table targets) under readable C
; names so the engine can call them without poking into LAB_xxxx
; addresses.
; -----------------------------------------------------------------

; TfmxCustom supplied by enclosing bridge			; Leonard's emulated $DFF000

; --- $DFF000 mirror addresses --------------------------------------
DMACON		=	TfmxCustom+$96
