AUTO_INT3	=	TfmxStubs+4		; was $6C     - IRQ vector slot
; EXT_0010 ($03F903C0) is NOT a real hw register - IRA found it in
; what is actually a DATA table inside the player (line ~1779,
; "SUBI.L #...,EXT_0010"). That "instruction" is never executed; the
; player reads those bytes as table data. We MUST emit the same raw
; bytes the Amiga original had, so we keep the literal IRA value
; (writes here would land in nothing, but no code ever issues them).
EXT_0010	=	$03F903C0


